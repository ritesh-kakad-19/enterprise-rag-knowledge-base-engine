import { env } from "../../config/env.js";

import type { PgVectorLiteral } from "./vector.types.js";

/**
 * Error thrown when an embedding vector is invalid.
 *
 * This is a normal Error because these utilities are
 * independent of HTTP request handling.
 */
export class VectorValidationError extends Error {
  constructor(message: string) {
    super(message);

    this.name = "VectorValidationError";
  }
}

/**
 * Validate an embedding vector.
 *
 * Checks:
 * 1. Vector is an array.
 * 2. Expected dimensions are valid.
 * 3. Vector is not empty.
 * 4. Vector has the expected number of dimensions.
 * 5. Every value is a finite number.
 *
 * @param vector - Embedding values generated by Gemini.
 * @param expectedDimensions - Expected vector dimensions.
 */
export function validateEmbeddingVector(
  vector: readonly number[],
  expectedDimensions: number = env.GEMINI_EMBEDDING_DIMENSIONS,
): void {
  // Ensure the input is actually an array.
  if (!Array.isArray(vector)) {
    throw new VectorValidationError(
      "Embedding vector must be an array.",
    );
  }

  // Expected dimensions must be a positive integer.
  if (
    !Number.isInteger(expectedDimensions) ||
    expectedDimensions <= 0
  ) {
    throw new VectorValidationError(
      "Expected vector dimensions must be a positive integer.",
    );
  }

  // Reject empty vectors.
  if (vector.length === 0) {
    throw new VectorValidationError(
      "Embedding vector cannot be empty.",
    );
  }

  // Ensure the vector matches our configured dimensions.
  if (vector.length !== expectedDimensions) {
    throw new VectorValidationError(
      `Invalid embedding dimensions. Expected ${expectedDimensions}, received ${vector.length}.`,
    );
  }

  // Ensure every value is a valid finite number.
  for (let index = 0; index < vector.length; index++) {
    const value = vector[index];

    if (
      typeof value !== "number" ||
      !Number.isFinite(value)
    ) {
      throw new VectorValidationError(
        `Invalid embedding value at index ${index}. Expected a finite number.`,
      );
    }
  }
}

/**
 * Convert a JavaScript embedding array into pgvector format.
 *
 * Example:
 *
 * Input:
 * [0.12, -0.45, 0.78]
 *
 * Output:
 * "[0.12,-0.45,0.78]"
 *
 * The returned string can later be passed as a parameter
 * to a PostgreSQL query.
 *
 * @param vector - Embedding values.
 * @param expectedDimensions - Expected vector dimensions.
 */
export function toPgVectorLiteral(
  vector: readonly number[],
  expectedDimensions: number = env.GEMINI_EMBEDDING_DIMENSIONS,
): PgVectorLiteral {
  // Validate before converting.
  validateEmbeddingVector(vector, expectedDimensions);

  // Convert the array into pgvector's text representation.
  const vectorLiteral = `[${vector.join(",")}]`;

  return vectorLiteral as PgVectorLiteral;
}